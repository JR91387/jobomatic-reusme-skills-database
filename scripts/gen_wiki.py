"""Generate the reference pages of the wiki (docs/wiki/) from the code, and check the wiki's links.

    python3 scripts/gen_wiki.py            write Table-Reference.md, MCP-Tools.md, Command-Line.md
    python3 scripts/gen_wiki.py --check    exit 1 if a generated page is stale or a link/image is broken

Table-Reference comes from schema_guide in a blank database, MCP-Tools from the @tool functions in
src/jobomatic/mcp_server.py, Command-Line from src/db.py --help. Never edit those three pages by hand."""
import argparse
import ast
import re
import sqlite3
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WIKI = ROOT / "docs" / "wiki"
sys.path.insert(0, str(ROOT / "src"))

from jobomatic import store

HEADER = "<!-- Generated by scripts/gen_wiki.py from {src}. Do not edit by hand. -->\n\n"


def _cell(text):
    return (text or "").replace("|", "\\|").replace("\n", " ").strip()


def table_reference():
    with tempfile.TemporaryDirectory() as d:
        db = Path(d) / "blank.db"
        store.new_database(db)
        conn = sqlite3.connect(db)
        guide = conn.execute(
            "SELECT object, column_name, kind, description, example FROM schema_guide").fetchall()
        types = {}
        for obj, in conn.execute("SELECT name FROM sqlite_master WHERE type IN ('table','view')"):
            for _cid, name, typ, notnull, _dflt, pk in conn.execute(f"PRAGMA table_info('{obj}')"):
                types[(obj, name)] = (typ or "", bool(notnull), bool(pk))
        conn.close()
    objects, columns, rules = {}, {}, {}
    for obj, col, kind, desc, ex in guide:
        if kind in ("table", "view"):
            objects[obj] = (kind, desc)
        elif kind == "column":
            columns.setdefault(obj, []).append((col, desc, ex))
        else:
            rules.setdefault(obj, []).append((col, desc))
    intro = ("Every table, view, column and rule, in the database's own words (`schema_guide`). "
             "See [[Data-Model]] for how they connect and [[Rules-and-Invariants]] for what is enforced.\n\n")
    out = [HEADER.format(src="src/db/schema_guide.sql"), "# Table reference\n\n", intro]
    out.append("| Object | Kind | What it holds |\n|---|---|---|\n")
    for obj in sorted(objects):
        kind, desc = objects[obj]
        out.append(f"| [`{obj}`](#{obj}) | {kind} | {_cell(desc)} |\n")
    for obj in sorted(objects):
        kind, desc = objects[obj]
        out.append(f"\n## {obj}\n\n*{kind}.* {desc}\n\n")
        if columns.get(obj):
            out.append("| Column | Type | Required | Meaning | Example |\n|---|---|---|---|---|\n")
            for col, cdesc, ex in columns[obj]:
                typ, notnull, pk = types.get((obj, col), ("", False, False))
                req = "key" if pk else ("yes" if notnull else "")
                out.append(f"| `{col}` | {typ} | {req} | {_cell(cdesc)} | {_cell(ex)} |\n")
        for name, rdesc in rules.get(obj, []):
            label = f"**{name}**: " if name else ""
            out.append(f"\n- Rule: {label}{rdesc}\n")
    return "".join(out)


def mcp_tools():
    src = ROOT / "src" / "jobomatic" / "mcp_server.py"
    tree = ast.parse(src.read_text(encoding="utf-8"))
    tools = []
    for node in tree.body:
        if not isinstance(node, ast.FunctionDef):
            continue
        for dec in node.decorator_list:
            if isinstance(dec, ast.Call) and getattr(dec.func, "id", "") == "tool":
                name = node.name
                for kw in dec.keywords:
                    if kw.arg == "name":
                        name = ast.literal_eval(kw.value)
                if dec.args:
                    name = ast.literal_eval(dec.args[0])
                tools.append((name, node))
    intro = ("The tools the Job-o-Matic MCP server offers to an MCP app. Start the server with "
             "`uvx job-o-matic-mcp` (pip install) or `python src/jobomatic/mcp_server.py [path/to/jobomatic.db]`; "
             "set `JOBOMATIC_DB` to choose the file. "
             "Every write is recorded as `ai`. Start with `schema_guide`; see [[Quick-Start-for-AI]].\n\n")
    out = [HEADER.format(src="src/jobomatic/mcp_server.py"), "# MCP tools\n\n", intro]
    out.append("| Tool | Summary |\n|---|---|\n")
    for name, node in tools:
        para = " ".join((ast.get_docstring(node) or "").split("\n\n")[0].split())
        first = para.split(". ")[0].rstrip(".") + "."
        out.append(f"| [`{name}`](#{name}) | {_cell(first)} |\n")
    for name, node in tools:
        args = node.args
        defaults = [None] * (len(args.args) - len(args.defaults)) + list(args.defaults)
        params = []
        for a, d in zip(args.args, defaults):
            typ = ast.unparse(a.annotation) if a.annotation else ""
            dv = "" if d is None else f" = {ast.unparse(d)}"
            params.append(f"`{a.arg}`" + (f": {typ}" if typ else "") + dv)
        out.append(f"\n## {name}\n\n")
        out.append(f"Parameters: {', '.join(params) if params else 'none'}\n\n")
        out.append((ast.get_docstring(node) or "").strip() + "\n")
    return "".join(out)


def command_line():
    helptext = subprocess.run([sys.executable, str(ROOT / "src" / "db.py"), "--help"],
                              capture_output=True, text=True, check=True).stdout
    helptext = re.sub(r"^usage: \S+", "usage: db.py", helptext)
    return (HEADER.format(src="src/db.py --help") + "# Command line\n\n"
            "For AIs that run commands (and for people who like a terminal): `job-o-matic-db` (pip install) or `src/db.py` reads and changes "
            "the database with plain SQL. In a download it is `app/src/db.py`, run with the bundled Python. "
            "Writes must set `updated_by` (see [[Rules-and-Invariants]]); the full column list is in "
            "[[Table-Reference]].\n\n```\n" + helptext.rstrip() + "\n```\n")


PAGES = {"Table-Reference.md": table_reference, "MCP-Tools.md": mcp_tools, "Command-Line.md": command_line}


def broken_links():
    pages = {p.stem for p in WIKI.glob("*.md")}
    bad = []
    for page in sorted(WIKI.glob("*.md")):
        text = page.read_text(encoding="utf-8")
        for m in re.finditer(r"\[\[([^\]]+)\]\]", text):
            target = m.group(1).split("|")[-1].strip()
            if target not in pages:
                bad.append(f"{page.name}: [[{m.group(1)}]]")
        for m in re.finditer(r"!\[[^\]]*\]\(([^)]+)\)", text):
            url = m.group(1)
            prefix = "https://raw.githubusercontent.com/JR91387/jobomatic-reusme-skills-database/main/"
            local = url.removeprefix(prefix)
            if not local.startswith("http") and not (ROOT / local).exists():
                bad.append(f"{page.name}: image {url}")
    return bad


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    WIKI.mkdir(parents=True, exist_ok=True)
    stale = []
    for name, fn in PAGES.items():
        text = fn()
        path = WIKI / name
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
    bad = broken_links()
    for s in stale:
        print(f"stale: {s}")
    for b in bad:
        print(f"broken: {b}")
    if stale or bad:
        print(f"❌ {len(stale)} stale, {len(bad)} broken")
        sys.exit(1)
    print(f"✅ {len(PAGES)} generated pages current, 0 broken links")


if __name__ == "__main__":
    main()
